"""Turn a file into a C++ byte array, for data the firmware carries whole (an
outline font for okapia_font_vector.cpp).

  usage: gen-blob.py <output .cpp> <symbol> <file> [<symbol> <file> ...]
"""
import sys


def main():
    if len(sys.argv) < 4 or len(sys.argv) % 2 != 0:
        raise SystemExit(__doc__)
    out_path, pairs = sys.argv[1], sys.argv[2:]
    with open(out_path, "w", encoding="utf-8") as out:
        out.write("// Generated by scripts/gen-blob.py — do not edit.\n\n")
        for i in range(0, len(pairs), 2):
            symbol, path = pairs[i], pairs[i + 1]
            data = open(path, "rb").read()
            out.write(f"// {path}, {len(data)} bytes\n")
            out.write(f"extern const unsigned char {symbol}[];\n")
            out.write(f"extern const unsigned {symbol}Size;\n")
            out.write(f"alignas (4) const unsigned char {symbol}[] =\n{{\n")
            for j in range(0, len(data), 20):
                out.write("\t" + ", ".join(f"0x{b:02X}" for b in data[j:j + 20]) + ",\n")
            out.write("};\n")
            out.write(f"const unsigned {symbol}Size = {len(data)};\n\n")


main()
