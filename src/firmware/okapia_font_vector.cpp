// The outline files, as bytes (generated by scripts/gen-blob.py).
extern const unsigned char OkapiaOutlineRegular[];
extern const unsigned char OkapiaOutlineBold[];

/*
 *  A weight: the outline, the glyph of each code, the kerning in units
 */
struct TWeight
{
    bool           bTried, bReady;
    stbtt_fontinfo Info;
    int           *pGlyph;              // FontGlyphIndex to the face's glyph, 0 none
    TOkapiaKern   *pKern;
    unsigned       nKern;
    int            nAscentUnits;        // the highest ink of any code, y up
    int            nDescentUnits;       // the lowest, negative
    int            nCapUnits;           // the H
};

static TWeight s_Weights[2];

static TWeight *Weight (bool bBold)
{
    TWeight &W = s_Weights[bBold ? 1 : 0];
    if (W.bTried)
    {
        return W.bReady ? &W : 0;
    }
    W.bTried = true;
    const unsigned char *pData = bBold ? OkapiaOutlineBold : OkapiaOutlineRegular;
    if (!stbtt_InitFont (&W.Info, pData, stbtt_GetFontOffsetForIndex (pData, 0)))
    {
        return 0;
    }
    const unsigned nCount = FontGlyphCount ();
    W.pGlyph = (int *) calloc (nCount, sizeof (int));
    if (W.pGlyph == 0)
    {
        return 0;
    }
    // Every code the faces carry, back from its index: the index is the code's
    // rank in FontGlyphIndex's ranges, so walk the codes up to the last one.
    unsigned nPresent = 0;
    for (int nCode = 0x20; nCode <= 0x2325; nCode++)
    {
        const int nIndex = FontGlyphIndex (nCode);
        if (nIndex < 0)
        {
            continue;
        }
        W.pGlyph[nIndex] = stbtt_FindGlyphIndex (&W.Info, nCode);
        if (W.pGlyph[nIndex] == 0)
        {
            continue;
        }
        nPresent++;
        int x0, y0, x1, y1;
        if (stbtt_GetGlyphBox (&W.Info, W.pGlyph[nIndex], &x0, &y0, &x1, &y1))
        {
            if (y1 > W.nAscentUnits)  W.nAscentUnits  = y1;
            if (y0 < W.nDescentUnits) W.nDescentUnits = y0;
        }
    }
    int x0, y0, x1, y1;
    W.nCapUnits = stbtt_GetCodepointBox (&W.Info, 'H', &x0, &y0, &x1, &y1) ? y1 - y0 : W.nAscentUnits;

    // The pairs, in index order so that FontKern16 can search them. Counted
    // first, then kept, so the table is exactly as large as it is.
    for (int nPass = 0; nPass < 2; nPass++)
    {
        unsigned n = 0;
        for (unsigned a = 0; a < nCount; a++)
        {
            if (W.pGlyph[a] == 0)
                continue;
            for (unsigned b = 0; b < nCount; b++)
            {
                if (W.pGlyph[b] == 0)
                    continue;
                const int nUnits = stbtt_GetGlyphKernAdvance (&W.Info, W.pGlyph[a], W.pGlyph[b]);
                if (nUnits == 0)
                    continue;
                if (nPass == 1)
                {
                    W.pKern[n].nLeft  = (unsigned short) a;
                    W.pKern[n].nRight = (unsigned short) b;
                    W.pKern[n].nUnits = (short) nUnits;
                }
                n++;
            }
        }
        if (nPass == 0)
        {
            W.pKern = (TOkapiaKern *) malloc ((n != 0 ? n : 1) * sizeof (TOkapiaKern));
            if (W.pKern == 0)
                return 0;
        }
        W.nKern = n;
    }
    (void) nPresent;
    W.bReady = true;
    return &W;
}

/*
 *  A face: one weight at one height
 */
static const TOkapiaGlyph s_NoGlyphs[1] = {};

// What a face is when nothing could be built: every index answers no ink and
// no advance. Indexed past its end on purpose by nobody: FontGlyphIndex's
// largest index is checked against nGlyphs below.
static TOkapiaFont s_Empty;
static TOkapiaGlyph *s_pEmptyGlyphs;

static const TOkapiaFont *Empty (unsigned nHeight)
{
    if (s_pEmptyGlyphs == 0)
    {
        s_pEmptyGlyphs = (TOkapiaGlyph *) calloc (FontGlyphCount (), sizeof (TOkapiaGlyph));
    }
    s_Empty.nHeight = nHeight;
    s_Empty.nAscent = nHeight * 3 / 4;
    s_Empty.nCapHeight = nHeight / 2;
    s_Empty.pGlyphs = s_pEmptyGlyphs != 0 ? s_pEmptyGlyphs : s_NoGlyphs;
    return &s_Empty;
}

// The cell at this scale from the glyphs' pixel boxes, so that an accented
// capital keeps its accent and a descender its tail, and the bytes their ink
// takes.
static void Cell (TWeight *pW, float fScale, int *pnAscent, int *pnDescent, size_t *pnBytes)
{
    int nAscent = 0, nDescent = 0;
    size_t nBytes = 0;
    for (unsigned i = 0; i < FontGlyphCount (); i++)
    {
        if (pW->pGlyph[i] == 0)
            continue;
        int x0, y0, x1, y1;
        stbtt_GetGlyphBitmapBox (&pW->Info, pW->pGlyph[i], fScale, fScale, &x0, &y0, &x1, &y1);
        if (-y0 > nAscent)  nAscent  = -y0;
        if (y1 > nDescent)  nDescent = y1;
        if (x1 > x0 && y1 > y0)
            nBytes += (size_t) (x1 - x0) * (size_t) (y1 - y0);
    }
    *pnAscent = nAscent;
    *pnDescent = nDescent;
    *pnBytes = nBytes;
}

static bool Build (TWeight *pW, unsigned nHeight, TOkapiaFont *pOut)
{
    const unsigned nCount = FontGlyphCount ();

    // The cell the theme asked for, to the row: pixel boxes round outwards, so
    // the scale that maps the ink to nHeight gives a row more, and at 640x480
    // the pages are laid out to the row. Brought down until it fits.
    float fScale = (float) nHeight / (float) (pW->nAscentUnits - pW->nDescentUnits);
    int nAscent, nDescent;
    size_t nBytes;
    Cell (pW, fScale, &nAscent, &nDescent, &nBytes);
    for (int nTry = 0; nTry < 8 && nAscent + nDescent > (int) nHeight; nTry++)
    {
        fScale *= ((float) nHeight - 0.25f) / (float) (nAscent + nDescent);
        Cell (pW, fScale, &nAscent, &nDescent, &nBytes);
    }

    TOkapiaGlyph *pGlyphs = (TOkapiaGlyph *) calloc (nCount, sizeof (TOkapiaGlyph));
    if (pGlyphs == 0)
    {
        return false;
    }
    unsigned char *pAlpha = (unsigned char *) malloc (nBytes != 0 ? nBytes : 1);
    if (pAlpha == 0)
    {
        free (pGlyphs);
        return false;
    }

    size_t nAt = 0;
    for (unsigned i = 0; i < nCount; i++)
    {
        const int g = pW->pGlyph[i];
        if (g == 0)
            continue;
        int nAdvance, nBearing;
        stbtt_GetGlyphHMetrics (&pW->Info, g, &nAdvance, &nBearing);
        TOkapiaGlyph &G = pGlyphs[i];
        G.nAdvance16 = (unsigned short) lroundf ((float) nAdvance * fScale * 16.0f);
        int x0, y0, x1, y1;
        stbtt_GetGlyphBitmapBox (&pW->Info, g, fScale, fScale, &x0, &y0, &x1, &y1);
        if (x1 <= x0 || y1 <= y0)
            continue;                   // the space: an advance and no ink
        G.nOffset = (unsigned) nAt;
        G.nWidth  = (unsigned char) (x1 - x0);
        G.nHeight = (unsigned char) (y1 - y0);
        G.nTop    = (unsigned char) (nAscent + y0);
        G.nLeft   = (signed char) x0;
        stbtt_MakeGlyphBitmap (&pW->Info, pAlpha + nAt, x1 - x0, y1 - y0, x1 - x0,
                               fScale, fScale, g);
        nAt += (size_t) (x1 - x0) * (size_t) (y1 - y0);
    }

    // The cap height as the eye takes it: the rows of the H at least half
    // covered, down to the baseline. Text is centred on it (GfxTextTop), and a
    // height rounded from the outline put every label a row high.
    unsigned nCap = (unsigned) lroundf ((float) pW->nCapUnits * fScale);
    const int nH = FontGlyphIndex ('H');
    if (nH >= 0 && pGlyphs[nH].nHeight != 0)
    {
        const TOkapiaGlyph &H = pGlyphs[nH];
        for (unsigned row = 0; row < H.nHeight; row++)
        {
            bool bDark = false;
            for (unsigned col = 0; col < H.nWidth && !bDark; col++)
            {
                bDark = pAlpha[H.nOffset + row * H.nWidth + col] >= 128;
            }
            if (bDark)
            {
                nCap = (unsigned) nAscent - (H.nTop + row);
                break;
            }
        }
    }

    pOut->nHeight    = (unsigned) (nAscent + nDescent);
    pOut->nAscent    = (unsigned) nAscent;
    pOut->nCapHeight = nCap;
    pOut->pGlyphs    = pGlyphs;
    pOut->pAlpha     = pAlpha;
    pOut->pKern      = pW->pKern;
    pOut->nKern      = pW->nKern;
    pOut->fKern16    = fScale * 16.0f;
    return true;
}

static const unsigned MAX_FACES = 24;

static struct
{
    unsigned    nHeight;
    bool        bBold;
    TOkapiaFont Face;
} s_Faces[MAX_FACES];
static unsigned s_nFaces;

static const TOkapiaFont *Face (unsigned nHeight, bool bBold)
{
    for (unsigned i = 0; i < s_nFaces; i++)
    {
        if (s_Faces[i].nHeight == nHeight && s_Faces[i].bBold == bBold)
        {
            return &s_Faces[i].Face;
        }
    }
    TWeight *pW = Weight (bBold);
    if (pW == 0 || s_nFaces == MAX_FACES || nHeight < 4 || nHeight > 255
        || !Build (pW, nHeight, &s_Faces[s_nFaces].Face))
    {
        return Empty (nHeight);
    }
    s_Faces[s_nFaces].nHeight = nHeight;
    s_Faces[s_nFaces].bBold   = bBold;
    return &s_Faces[s_nFaces++].Face;
}

const TOkapiaFontSet *FontNearest (unsigned nHeight)
{
    static const unsigned MAX_SETS = 12;
    static TOkapiaFontSet s_Sets[MAX_SETS];
    static unsigned s_nSets;
    for (unsigned i = 0; i < s_nSets; i++)
    {
        if (s_Sets[i].nHeight == nHeight)
        {
            return &s_Sets[i];
        }
    }
    static TOkapiaFontSet s_Spare;
    TOkapiaFontSet &S = s_nSets < MAX_SETS ? s_Sets[s_nSets++] : s_Spare;
    S.nHeight  = nHeight;
    S.pRegular = Face (nHeight, false);
    S.pBold    = Face (nHeight, true);
    return &S;
}

const TOkapiaFont *FontBoldWithCap (unsigned nCap)
{
    TWeight *pW = Weight (true);
    if (pW == 0 || pW->nCapUnits <= 0 || nCap == 0)
    {
        return Empty (nCap * 3 / 2 + 1);
    }
    // The cell whose H is nCap tall, then down a row while rounding made it
    // taller: "at most" is what a mark inside a frame needs.
    unsigned nHeight = (unsigned) ((float) nCap * (float) (pW->nAscentUnits - pW->nDescentUnits)
                                   / (float) pW->nCapUnits);
    const TOkapiaFont *pFace = Face (nHeight, true);
    while (pFace->nCapHeight > nCap && nHeight > 4)
    {
        pFace = Face (--nHeight, true);
    }
    return pFace;
}
